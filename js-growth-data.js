/* ---------- Trova la riga più vicina per un dato mese (arrotonda) ---------- */
function whoRowForMonth(table, months) {
  const m = Math.max(0, Math.min(60, Math.round(months)));
  return table[m] || table[table.length - 1];
}

/* Interpola percentile stimato del bambino data la sua età (mesi) e valore misurato.
   Usa interpolazione lineare tra le curve percentili più vicine per una stima approssimativa
   (non è un calcolo Z-score esatto, ma sufficiente per capire "dove si trova"). */
function estimatePercentile(table, months, value) {
  const row = whoRowForMonth(table, months);
  const [, p3, p15, p50, p85, p97] = row;
  const points = [[3,p3],[15,p15],[50,p50],[85,p85],[97,p97]];
  if (value <= p3) return '<3';
  if (value >= p97) return '>97';
  for (let i = 0; i < points.length - 1; i++) {
    const [pa, va] = points[i];
    const [pb, vb] = points[i+1];
    if (value >= va && value <= vb) {
      const frac = (value - va) / (vb - va);
      const pct = Math.round(pa + frac * (pb - pa));
      return String(pct);
    }
  }
  return '50';
}

function getGrowthTable(measureType, gender) {
  const isGirl = gender === 'F';
  if (measureType === 'weight') return isGirl ? WHO_WEIGHT_GIRLS : WHO_WEIGHT_BOYS;
  if (measureType === 'height') return isGirl ? WHO_HEIGHT_GIRLS : WHO_HEIGHT_BOYS;
  if (measureType === 'head') return isGirl ? WHO_HEAD_GIRLS : WHO_HEAD_BOYS;
  return WHO_WEIGHT_BOYS;
}
